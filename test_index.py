"""Repo-wide checks that back INDEX.md and the deploy routine.

INDEX.md is generated by build_index.py. If this fails with "stale", run
`python build_index.py` and commit the result.
"""
import build_index as bi


def test_index_is_current():
    expected = bi.build()
    current = bi.INDEX.read_text(encoding="utf-8") if bi.INDEX.exists() else ""
    assert current == expected, "INDEX.md is stale: run `python build_index.py`"


def test_every_cog_has_a_detectable_version():
    missing = [c["dir"] for c in (bi.analyse(d, []) for d in bi.cog_dirs()) if c["version"] == "n/a"]
    assert not missing, f"no version constant or build string found in: {missing}"


def test_info_json_sits_directly_in_each_cog_folder():
    """A cog folder (has __init__.py) without info.json beside it will not install."""
    orphans = [
        p.parent.name
        for p in bi.ROOT.glob("*/__init__.py")
        if not p.parent.name.startswith(("_", ".")) and not (p.parent / "info.json").exists()
    ]
    assert not orphans, f"missing info.json directly in: {orphans}"


def test_no_command_name_collisions_between_cogs():
    cogs = [bi.analyse(d, []) for d in bi.cog_dirs()]
    clashes = bi.command_clashes(cogs)
    assert not clashes, f"top-level command names claimed by more than one cog: {clashes}"
